"""Converts the C++ firmware's screen assets for the Rust firmware.

Run from the repository root, with freetype-py installed (pip install freetype-py):

    python v2r/tools/assets.py

It writes, under v2r/firmware/assets:

- one .rgb565 file per 320 x 170 background of src/media/images_320_170.h, as
  big-endian RGB565 ready for the panel;
- fonts.rs: the glyphs of the TrueType fonts in src/media/myFonts.h, rendered
  with FreeType at every size the screens use, with the metrics that
  OpenFontRender reads when it lays text out; then the TFT_eSPI bitmap fonts
  the screens use: Adafruit GFX free fonts and the built-in Font 2.
"""

import pathlib
import re

import freetype

ROOT = pathlib.Path(__file__).resolve().parents[2]
MEDIA = ROOT / "src" / "media"
OUT = ROOT / "v2r" / "firmware" / "assets"

WIDTH, HEIGHT = 320, 170

IMAGES = {
    "MinerScreen": "miner",
    "minerClockScreen": "clock",
    "globalHashScreen": "global_hash",
    "priceScreen": "price",
    "initScreen": "init",
    "setupModeScreen": "setup",
}

# Font sizes passed to OpenFontRender::setFontSize by the T-Display screens.
FONTS = {
    "DigitalNumbers": [4, 10, 14, 17, 18, 24, 25, 28, 35],
}

TFT_ESPI = ROOT / "lib" / "TFT_eSPI" / "Fonts"

# Free fonts the T-Display screens select: FSS9, FSSB9, FF23 and FF24.
GFX_FONTS = {
    "FreeSans9pt7b": "FREE_SANS_9",
    "FreeSansBold9pt7b": "FREE_SANS_BOLD_9",
    "FreeSansBold18pt7b": "FREE_SANS_BOLD_18",
    "FreeSansBold24pt7b": "FREE_SANS_BOLD_24",
}

# What User_Setup leaves defined for Font16.c: a dollar sign, and a degree
# sign in place of the grave accent.
FONT2_DEFINES = {"TFT_ESPI_FONT2_DOLLAR", "TFT_ESPI_GRAVE_IS_DEGREE"}

CHARS = "".join(chr(c) for c in range(0x20, 0x7F))


def c_array(source: str, name: str) -> list[int]:
    # Comments can sit anywhere, and the image arrays end each line with one
    # counting pixels, "// 0x0010 (16)": their numbers are not data.
    source = re.sub(r"//[^\n]*|/\*.*?\*/", "", source, flags=re.S)
    match = re.search(r"\b" + name + r"\s*\[[^\]]*\]\s*(?:PROGMEM)?\s*=\s*\{(.*?)\};", source, re.S)
    if not match:
        raise SystemExit(f"{name} not found")
    # Each line ends with a comment counting pixels, "// 0x0010 (16)": its
    # numbers are not data.
    body = re.sub(r"//[^\n]*|/\*.*?\*/", "", match.group(1), flags=re.S)
    return [int(value, 0) for value in re.findall(r"0x[0-9A-Fa-f]+|\b\d+\b", body)]


def images() -> None:
    source = (MEDIA / "images_320_170.h").read_text(encoding="utf-8", errors="replace")
    for array, name in IMAGES.items():
        pixels = c_array(source, array)[: WIDTH * HEIGHT]
        if len(pixels) != WIDTH * HEIGHT:
            raise SystemExit(f"{array} has {len(pixels)} pixels")
        data = b"".join(pixel.to_bytes(2, "big") for pixel in pixels)
        (OUT / f"{name}.rgb565").write_bytes(data)
        print(f"{name}.rgb565: {len(data)} bytes")


def glyphs(face: freetype.Face, size: int) -> tuple[int, list[str]]:
    face.set_pixel_sizes(0, size)
    ascender = face.size.ascender >> 6
    rows = []
    for char in CHARS:
        if face.get_char_index(char) == 0 and char != " ":
            continue
        # The layout pass: FT_LOAD_DEFAULT, then the grid-fitted box.
        face.load_char(char, freetype.FT_LOAD_DEFAULT)
        bearing = face.glyph.metrics.horiBearingX >> 6
        glyph = face.glyph.get_glyph()
        box = glyph.get_cbox(freetype.FT_GLYPH_BBOX_PIXELS)
        # FT_Glyph keeps the slot's hinted advance, in 16.16 instead of 26.6.
        advance = face.glyph.advance.x >> 6
        # The drawing pass: FT_LOAD_RENDER, an 8-bit coverage bitmap.
        face.load_char(char, freetype.FT_LOAD_RENDER)
        bitmap = face.glyph.bitmap
        alpha = bytearray()
        for y in range(bitmap.rows):
            start = y * bitmap.pitch
            alpha += bytes(bitmap.buffer[start : start + bitmap.width])
        rows.append(
            f"        Glyph {{ ch: {ord(char)}, advance: {advance}, x_min: {box.xMin}, x_max: {box.xMax}, "
            f"bearing: {bearing}, left: {face.glyph.bitmap_left}, top: {face.glyph.bitmap_top}, "
            f"width: {bitmap.width}, rows: {bitmap.rows}, alpha: &{list(alpha)} }},"
        )
    return ascender, rows


def fonts() -> None:
    source = (MEDIA / "myFonts.h").read_text(encoding="utf-8", errors="replace")
    lines = [
        "// Generated by v2r/tools/assets.py from src/media/myFonts.h: do not edit.",
        "",
        "use crate::text::{Font, Glyph};",
        "",
    ]
    for array, sizes in FONTS.items():
        data = bytes(c_array(source, array))
        face = freetype.Face(_temporary(array, data))
        for size in sizes:
            ascender, rows = glyphs(face, size)
            const = f"{_snake(array).upper()}_{size}"
            lines.append(f"pub static {const}: Font = Font {{")
            lines.append(f"    ascender: {ascender},")
            lines.append("    glyphs: &[")
            lines.extend(rows)
            lines.append("    ],")
            lines.append("};")
            lines.append("")
    lines += gfx_fonts()
    lines += font2()
    (OUT / "fonts.rs").write_text("\n".join(lines), encoding="utf-8")
    print(f"fonts.rs: {sum(len(s) for s in FONTS.values())} sizes")


def preprocess(source: str, defines: set[str]) -> str:
    """Keeps the branches of #ifdef / #else / #endif that `defines` select."""
    out, stack = [], []
    for line in source.splitlines():
        directive = line.strip()
        if directive.startswith("#ifdef"):
            stack.append(directive.split()[1] in defines)
        elif directive.startswith("#ifndef"):
            stack.append(directive.split()[1] not in defines)
        elif directive.startswith("#else"):
            stack[-1] = not stack[-1]
        elif directive.startswith("#endif"):
            stack.pop()
        elif all(stack):
            out.append(line)
    return "\n".join(out)


def gfx_fonts() -> list[str]:
    lines = ["use crate::text::{GfxFont, GfxGlyph, Font2};", ""]
    for name, const in GFX_FONTS.items():
        source = (TFT_ESPI / "GFXFF" / f"{name}.h").read_text(encoding="utf-8", errors="replace")
        bitmap = c_array(source, f"{name}Bitmaps")
        body = re.search(name + r"Glyphs\[\]\s*PROGMEM\s*=\s*\{(.*?)\};", source, re.S).group(1)
        body = re.sub(r"//[^\n]*", "", body)
        glyphs = [list(map(int, g.split(","))) for g in re.findall(r"\{([^}]*)\}", body)]
        first, last = (int(v, 0) for v in re.search(
            r"GFXfont\s+" + name + r"\s+PROGMEM\s*=\s*\{[^,]*,[^,]*,\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)",
            source).groups())
        lines.append(f"pub static {const}: GfxFont = GfxFont {{")
        lines.append(f"    first: {first},")
        lines.append(f"    last: {last},")
        lines.append(f"    bitmap: &{bitmap},")
        lines.append("    glyphs: &[")
        for offset, width, height, advance, x_offset, y_offset in glyphs:
            lines.append(
                f"        GfxGlyph {{ offset: {offset}, width: {width}, height: {height}, advance: {advance}, "
                f"x_offset: {x_offset}, y_offset: {y_offset} }},"
            )
        lines.append("    ],")
        lines.append("};")
        lines.append("")
    return lines


def font2() -> list[str]:
    source = preprocess((TFT_ESPI / "Font16.c").read_text(encoding="utf-8", errors="replace"), FONT2_DEFINES)
    widths = c_array(source, "widtbl_f16")
    if len(widths) != 96:
        raise SystemExit(f"widtbl_f16 has {len(widths)} widths")
    rows = []
    for code in range(0x20, 0x80):
        data = c_array(source, f"chr_f16_{code:02X}")
        rows.append(f"        &{data},")
    return [
        "/// TFT_eSPI's Font 2: 16 rows, the baseline after 13.",
        "pub static FONT_2: Font2 = Font2 {",
        f"    widths: {widths},",
        "    glyphs: [",
        *rows,
        "    ],",
        "};",
        "",
    ]


def _temporary(name: str, data: bytes) -> str:
    path = OUT / f".{name}.ttf"
    path.write_bytes(data)
    return str(path)


def _snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    images()
    fonts()
    for path in OUT.glob(".*.ttf"):
        path.unlink()
